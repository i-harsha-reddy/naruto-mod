// The haori team's effects (Madara, Jiraiya), each family's frames hand-tuned
// from drafts. Registered in fx/index.ts as one entry (HAORI_FX).
//
// FIRE (Madara's Great Fire Annihilation), palette 'fire', every family
// anchored on his lips at grid [31, 21] (the grid's columns 0-31 are the
// stage's 0-31 when placed at the lips [28, 17] braced; its first four rows
// are above the stage, cropped): the biggest fire in the mod.
//   fireWall   4 frames: a ball of flame rolling out of the lips (front at
//              about x 10), doubled and down on the ground over the post,
//              stood up into a wall cresting left, then the wall itself, the
//              stage's height (cropped at the top), 32 wide. Drawn back:
//              he is braced in front of it.
//   fireField  3 frames: the wall burning on, tall tongues at the back,
//              shorter in front, white-hot at its foot ('cycle').
//   fireDie    4 frames: the field sunk to half, a third, licks along the
//              ground, the last licks round the post's foot.
//   fireJet    3 frames: the ragged jet out of his lips in front of his face
//              ('cycle', on 'head' + the mouth).
// THE RASENGAN (Jiraiya's Giant Rasengan), palette 'rasen', anchored on the
// post's struck face ('post'):
//   rasenGrind 3 frames: the ball fed past its charge, 19 px, ground into
//              the post (bigger than any frame before it), its swirl and
//              three solid crescents of wind hugging it a sixth of a turn a
//              frame.
//   rasenBurst 4 frames: white through the wood (19 px), a disc of torn wind
//              (24), the wind's blades flung round (25), their last (26).
// THE SUSANOO (fx/summons/susanoo.ts): susanooCage (behind him) and
// susanooRibs (round him), anchored on his feet at [33, GROUND].
// TENGAI SHINSEI (fx/summons/meteor.ts): meteorCrack, the first rock as it
// sits on the post, cracking a frame at a time (never re-forming).
// GAMABUNTA (fx/summons/toad.ts): toadFace, the bust whole with a blink and
// a puff, for the summoning's climax.
// NEEDLE JIZŌ (Jiraiya): jizoNeedles, anchored on the post's struck face
// ('post'): three hair needles, each a dark-outlined white spike pointing
// at the post with a short streak behind it, 0 in flight (ten pixels off),
// 1 nearly there, 2 stuck in the wood (their tails out of its face), 3 the
// tails quivering (a pixel longer, shorter, longer).
// SAGE MODE (Jiraiya): sageToads, the two old toads Fukasaku and Shima
// sitting on his shoulders, anchored on his head's top-left ('head', d to
// the shoulders), drawn in front: Fukasaku on the post's side with his white
// brows, Shima on the far side with her pink lips; 3 frames (sitting; Pa
// blinks; Ma's throat puffs; again by his turned head).
