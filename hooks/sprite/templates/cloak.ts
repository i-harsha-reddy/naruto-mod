// The 'cloak' outfit template: the Akatsuki's long black cloak, worn closed,
// red-lined, with the high stand-up collar framing the chin, wide sleeves the
// hands come out of, and the hem at mid-shin over sandals (Itachi, Kisame,
// Deidara, Pain, Obito). Drawn once, in SEMANTIC letters (as templates/vest.ts
// is); each ninja who wears it maps them to colours in their own file
// (ninja/<id>.ts's `body`, the cloak's own colours shared: CLOAK_COLOURS):
//   o          outline
//   s k        skin, skin shadow (hands)
//   v w x      the cloak: lit, mid, shadow (a deep navy-black; the darkest
//              fill stays at luma 62+ so it holds on a dark terminal)
//   n m        the red lining: lit (the collar's inside), shadow (the front
//              closure, the inside of a sleeve)
//   c b        a cloud: red, and its white rim (3 x 2 clouds, placed by hand)
//   p q        trousers, where a stride shows the legs: lit, shadow
//   t u        sandals: shadow, lit
//   y z        hair, light and shadow (smears)
//   a e d      a held prop: main, shadow, light (Itachi's kunai, Pain's
//              chakra rod, Deidara's clay); a ninja who carries none maps
//              them clear (a:-)
// UPPERCASE: the same colour drawn OVER the head (the collar's flaps, hands at
// the face). Light from the top left.
//
// The poses are the vest's (same names, head offsets and companion poses, so
// one choreography fits both outfits), drawn 26 columns wide with the point
// between the feet in column 13 and the last row on the feet. Their hands
// sit where this cloak's sleeves put them: the strike's at [0, 9], the
// follow-through's at [0, 10], the punch's at [1, 8].
//
// WHAT IS A NINJA'S OWN is in their file (ninja/<id>.ts), in the NinjaSprite's
// own fields (types.ts's top): poses of their own (Itachi's two-finger seal,
// Kisame's swings of Samehada), overlays on a pose (Deidara's clay pouch at
// the hip), props worn that ride with the head (Samehada on Kisame's back).

