// The 'top' outfit template: a chibi in a fitted top with a belt or sash, a
// short skirt (or a coat's skirts) over shorts or trousers, and sandals or
// boots (Sakura, Tsunade). Drawn once, in SEMANTIC letters; each ninja who
// wears it maps them to colours in their own file (ninja/<id>.ts's `body`):
//   o          outline
//   s k        hands: lit, shadow (Sakura's gloves, Tsunade's skin)
//   v w x      the top: lit, mid, shadow (Sakura's red top, Tsunade's grey kimono)
//   n m l      arms / sleeves: lit, mid, shadow (Sakura's bare arms, Tsunade's
//              haori sleeves)
//   g h        elbow pads: lit, shadow (Sakura's; Tsunade maps them to her sleeve)
//   c          a mark on the chest (Sakura's white circle; Tsunade: the kimono)
//   b          the belt row: Sakura's skirt waistband, Tsunade's sash
//   f i j      the skirt: lit, mid, shadow (Sakura's apron skirt, Tsunade's
//              haori skirts)
//   p q r      shorts / trousers / boots: lit, mid, shadow
//   t u        feet: shadow, lit
//   a e d      a held prop: main, ends, detail (the roundel on Tsunade's haori)
//   y z        hair, light and shadow (for smears and afterimages)
// UPPERCASE: the same colour drawn OVER the head (a hand in front of the
// face). Light from the top left.
//
// Under these heads the body shows about 6 rows: the bobbed hair and the
// pigtails hang to the shoulders, so the arms read below the chin or out past
// the hair, and the head dips less than the vest's (dy 1-2, not 2-3) so the
// top, skirt and legs stay visible in the action poses. An arm crossing the
// face is outlined in UPPERCASE where it meets it.
//
// Each pose: rows (26 wide or more, root column 13, last row on the feet),
// as (the companion pose it stands for), head [dx, dy], hand [x, y] (the
// acting hand, for effects; in some poses it sits a pixel off the vest's:
// strike [1, 7], punch [2, 7]), eyes (its default eye state: the states a
// pose names, open left half shut focus happy sad wide shout, must be in
// every wearer's eyes), breath (its other breathing frame). Drawn in the
// prototype in 31 poses: every companion pose its
// own drawing, plus the breath (idle1), the dash's smear, the
